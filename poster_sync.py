"""
Poster Sync & Watcher for POSSE Portfolio
Designed for GitHub Pages & Local Development

Features:
- Scans 'Posters & graphic design/' for images (.png, .jpg, .jpeg, .webp).
- Sorts by recently added (newest creation/modification time on top).
- Automatically optimizes web-ready images into 'assets/posters/' (under 200KB each)
  so GitHub Pages loads super fast on mobile and desktop.
- Automatically generates 'js/posters-data.js' containing the sorted poster list.
- Supports continuous watch mode: drop an image in the folder and it updates in seconds.
"""

import os
import sys
import time
from pathlib import Path
from PIL import Image

WORKSPACE_DIR = Path(__file__).resolve().parent
SOURCE_DIR = WORKSPACE_DIR / "Posters & graphic design"
OPTIMIZED_DIR = WORKSPACE_DIR / "assets" / "posters"
DATA_FILE = WORKSPACE_DIR / "js" / "posters-data.js"

SUPPORTED_EXTS = {".png", ".jpg", ".jpeg", ".webp"}
MAX_DIMENSION = 1400  # Max width/height for web preview
JPEG_QUALITY = 85     # Good balance of crispness and small file size


def get_file_timestamp(path: Path) -> float:
    """Returns the most recent of creation or modification time."""
    stat = path.stat()
    return max(stat.st_ctime, stat.st_mtime)


def optimize_image(src_path: Path, dest_path: Path) -> bool:
    """Creates a compressed, web-ready JPEG if not already created or if source is newer."""
    try:
        if dest_path.exists():
            if dest_path.stat().st_mtime >= src_path.stat().st_mtime:
                return False  # Already up-to-date

        dest_path.parent.mkdir(parents=True, exist_ok=True)

        with Image.open(src_path) as img:
            # Convert RGBA / P / CMYK to RGB for JPEG
            if img.mode in ("RGBA", "LA", "P"):
                # Use white background for transparent areas
                bg = Image.new("RGB", img.size, (10, 10, 10))  # dark bg matching portfolio theme
                if img.mode != "RGBA":
                    img = img.convert("RGBA")
                bg.paste(img, mask=img.split()[3])
                img = bg
            elif img.mode != "RGB":
                img = img.convert("RGB")

            # Downscale only if larger than MAX_DIMENSION
            w, h = img.size
            if max(w, h) > MAX_DIMENSION:
                img.thumbnail((MAX_DIMENSION, MAX_DIMENSION), Image.Resampling.LANCZOS)

            img.save(dest_path, "JPEG", quality=JPEG_QUALITY, optimize=True)
            return True
    except Exception as e:
        print(f"[!] Warning: Failed to optimize {src_path.name}: {e}")
        return False


def sync_posters(verbose: bool = True) -> int:
    """Scans, sorts, optimizes, and generates js/posters-data.js."""
    if not SOURCE_DIR.exists():
        print(f"[!] Source directory not found: {SOURCE_DIR}")
        return 0

    files = [
        f for f in SOURCE_DIR.iterdir()
        if f.is_file() and f.suffix.lower() in SUPPORTED_EXTS
    ]

    if not files:
        if verbose:
            print("[i] No images found in 'Posters & graphic design'.")
        return 0

    # Sorting algorithm: Recently added / updated files on TOP (descending by timestamp)
    files.sort(key=get_file_timestamp, reverse=True)

    items = []
    new_optimizations = 0

    for file_path in files:
        timestamp = get_file_timestamp(file_path)
        base_name = file_path.stem
        # Dest preview name
        dest_name = f"{base_name}.jpg"
        dest_path = OPTIMIZED_DIR / dest_name

        if optimize_image(file_path, dest_path):
            new_optimizations += 1

        # Use relative web-safe forward slashes
        web_src = f"assets/posters/{dest_name}" if dest_path.exists() else f"Posters & graphic design/{file_path.name}"
        web_full_src = f"Posters & graphic design/{file_path.name}"

        items.append({
            "title": base_name,
            "src": web_src,
            "fullSrc": web_full_src,
            "timestamp": int(timestamp)
        })

    # Generate js/posters-data.js
    import json
    js_content = "/* Auto-generated by poster_sync.py — Do not edit manually */\n"
    js_content += "window.PORTFOLIO_POSTERS = " + json.dumps(items, indent=2) + ";\n"

    DATA_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        f.write(js_content)

    if verbose:
        print(f"[✓] Successfully synced {len(items)} poster(s).")
        if new_optimizations > 0:
            print(f"    - Optimized {new_optimizations} new/modified image(s) for fast GitHub Pages loading.")
        print(f"    - Updated: {DATA_FILE.relative_to(WORKSPACE_DIR)}")
        print(f"    - #1 Most Recent on Top: {items[0]['title']}")

    return len(items)


def git_auto_push(commit_msg: str):
    """Optionally commits and pushes changes to GitHub."""
    import subprocess
    try:
        subprocess.run(["git", "add", "Posters & graphic design", "assets/posters", "js/posters-data.js"], check=True)
        # Check if there are staged changes
        res = subprocess.run(["git", "diff", "--staged", "--quiet"])
        if res.returncode != 0:
            subprocess.run(["git", "commit", "-m", commit_msg], check=True)
            print("[↑] Pushing to GitHub...")
            subprocess.run(["git", "push"], check=True)
            print("[✓] Pushed to GitHub Pages successfully!")
    except Exception as e:
        print(f"[!] Git push skipped or failed: {e}")


def watch_mode(auto_push: bool = False):
    """Continuously monitors 'Posters & graphic design' for changes."""
    print("=" * 60)
    print("  POSSE Portfolio — Real-time Poster Watcher (GitHub-Ready)")
    print(f"  Watching: {SOURCE_DIR}")
    print("  Drop any image (.png, .jpg, .webp) into the folder!")
    if auto_push:
        print("  Auto-Git Push: ENABLED (Changes will push to GitHub)")
    else:
        print("  Auto-Git Push: OFF (Run 'git push' when ready to deploy)")
    print("  Press Ctrl+C to stop.")
    print("=" * 60)

    # Initial sync
    sync_posters(verbose=True)

    def get_snapshot():
        if not SOURCE_DIR.exists():
            return {}
        return {
            f.name: get_file_timestamp(f)
            for f in SOURCE_DIR.iterdir()
            if f.is_file() and f.suffix.lower() in SUPPORTED_EXTS
        }

    last_snapshot = get_snapshot()

    try:
        while True:
            time.sleep(1.5)
            current_snapshot = get_snapshot()

            if current_snapshot != last_snapshot:
                added = set(current_snapshot.keys()) - set(last_snapshot.keys())
                modified = {k for k in current_snapshot if k in last_snapshot and current_snapshot[k] != last_snapshot[k]}
                deleted = set(last_snapshot.keys()) - set(current_snapshot.keys())

                if added:
                    print(f"\n[+] Detected new file(s): {', '.join(added)}")
                if modified:
                    print(f"\n[*] Detected modified file(s): {', '.join(modified)}")
                if deleted:
                    print(f"\n[-] Detected deleted file(s): {', '.join(deleted)}")

                count = sync_posters(verbose=True)

                if auto_push:
                    msg = f"Add new poster: {', '.join(added)}" if added else "Update posters feed"
                    git_auto_push(msg)

                last_snapshot = current_snapshot
    except KeyboardInterrupt:
        print("\nWatcher stopped.")


if __name__ == "__main__":
    auto_push = "--push" in sys.argv
    if "--watch" in sys.argv:
        watch_mode(auto_push=auto_push)
    else:
        sync_posters(verbose=True)
        if auto_push:
            git_auto_push("Sync posters feed")
